# Bangla lekha ke OLED er jonno 1-bit chhobi (bitmap) banay.
# "Nirmala UI" font, 1-bit hinted mode e ake (Windows er text engine), tai juktoborno ar kar thik thake
# ar choto OLED e akkhor dhardhare dekhay. Onno font try korte: -FontName "Font er naam"
# Json e protita line: id, text, size (pixel), bold (true/false, optional), en (English mode), group (optional: eki group = eki uchchota).
#
# Chalano:  powershell -ExecutionPolicy Bypass -File tools\make_bangla.ps1
# Notun lekha jog korte bangla_text.json e line jog koro, tarpor abar chalao.
# Output:   PetBot\bangla_text.h  +  tools\preview\bangla_preview.png

param(
  [string]$Json       = "$PSScriptRoot\bangla_text.json",
  [string]$OutH       = "$PSScriptRoot\..\PetBot\bangla_text.h",
  [string]$PreviewDir = "$PSScriptRoot\preview",
  [int]$Threshold     = 128,
  [string]$FontName   = "Nirmala UI",
  [bool]$Mono         = $true         # 1-bit hinted rendering: choto OLED e sobcheye dhardhare
)

Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName System.Windows.Forms

$items = Get-Content -Raw -Encoding UTF8 $Json | ConvertFrom-Json
New-Item -ItemType Directory -Force $PreviewDir | Out-Null

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Auto-generated by tools/make_bangla.ps1 from tools/bangla_text.json")
[void]$sb.AppendLine("// Hate edit koro na - json bodle script abar chalao.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("#include <Arduino.h>")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("// en = English mode e ei lekhar bodole ja dekhabe (nullptr = English nei)")
[void]$sb.AppendLine("// Flash (PROGMEM) e thake: tai shob ghor 32-bit (ESP8266 flash theke shudhu 32-bit pora jay)")
[void]$sb.AppendLine("// volatile: compiler jate 16-bit kore na pore (flash e 16-bit pora = crash)")
[void]$sb.AppendLine("// enP: English lekha, eta-o flash e (PROGMEM) - porte enStr(b) bebohar koro")
[void]$sb.AppendLine("struct BnText { volatile int32_t w; volatile int32_t h; const uint8_t* bmp; const char* enP; };")
[void]$sb.AppendLine("")

$rendered = @()
$flags = [System.Windows.Forms.TextFormatFlags]::NoPadding -bor [System.Windows.Forms.TextFormatFlags]::SingleLine

$pass = @()
foreach ($it in $items) {
  $style = if ($it.bold) { [System.Drawing.FontStyle]::Bold } else { [System.Drawing.FontStyle]::Regular }
  $font = New-Object System.Drawing.Font($FontName, [float]$it.size, $style, [System.Drawing.GraphicsUnit]::Pixel)
  if ($font.Name -ne $FontName) { throw "Font '$FontName' pawa jay ni (pelam '$($font.Name)')" }
  $sz = [System.Windows.Forms.TextRenderer]::MeasureText($it.text, $font, (New-Object System.Drawing.Size(2000, 400)), $flags)
  $W = $sz.Width + 10; $H = $sz.Height + 10

  $img = New-Object System.Drawing.Bitmap($W, $H)
  $g = [System.Drawing.Graphics]::FromImage($img)
  $g.Clear([System.Drawing.Color]::Black)
  if ($Mono) { $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit }
  [System.Windows.Forms.TextRenderer]::DrawText($g, $it.text, $font, (New-Object System.Drawing.Point(5, 5)),
      [System.Drawing.Color]::White, [System.Drawing.Color]::Black, $flags)
  $g.Dispose()

  # Kali kothay ache (ink bounds) khuje ber kora
  $minX = $W; $minY = $H; $maxX = -1; $maxY = -1
  $on = New-Object 'bool[,]' $W, $H
  for ($y = 0; $y -lt $H; $y++) {
    for ($x = 0; $x -lt $W; $x++) {
      $c = $img.GetPixel($x, $y)
      $v = [Math]::Max($c.R, [Math]::Max($c.G, $c.B))
      if ($v -ge $Threshold) {
        $on[$x, $y] = $true
        if ($x -lt $minX) { $minX = $x }; if ($x -gt $maxX) { $maxX = $x }
        if ($y -lt $minY) { $minY = $y }; if ($y -gt $maxY) { $maxY = $y }
      }
    }
  }
  $img.Dispose()
  $pass += [pscustomobject]@{ it = $it; on = $on; minX = $minX; maxX = $maxX; minY = $minY; maxY = $maxY }
}

# Eki "group" er sob lekha eki uchchotay kata hoy (jate shonkhya + shobdo pashapashi boshale line thik thake)
$gmin = @{}; $gmax = @{}
foreach ($p in $pass) {
  $g = $p.it.group; if (-not $g) { continue }
  if (-not $gmin.ContainsKey($g) -or $p.minY -lt $gmin[$g]) { $gmin[$g] = $p.minY }
  if (-not $gmax.ContainsKey($g) -or $p.maxY -gt $gmax[$g]) { $gmax[$g] = $p.maxY }
}

foreach ($p in $pass) {
  $it = $p.it; $on = $p.on; $minX = $p.minX; $maxX = $p.maxX; $minY = $p.minY; $maxY = $p.maxY
  if ($it.group) { $minY = $gmin[$it.group]; $maxY = $gmax[$it.group] }
  $bw = $maxX - $minX + 1; $bh = $maxY - $minY + 1
  if ($bw -gt 128) { Write-Warning "$($it.id) chowra $bw px, 128 er beshi!" }

  # 1-bit pack (Adafruit drawBitmap format: row by row, MSB first)
  $bytesPerRow = [int][Math]::Ceiling($bw / 8)
  $bytes = New-Object System.Collections.Generic.List[string]
  for ($y = 0; $y -lt $bh; $y++) {
    for ($bx = 0; $bx -lt $bytesPerRow; $bx++) {
      $b = 0
      for ($k = 0; $k -lt 8; $k++) {
        $x = $bx * 8 + $k
        if ($x -lt $bw -and ($minY + $y) -lt $on.GetLength(1) -and $on[($minX + $x), ($minY + $y)]) { $b = $b -bor (0x80 -shr $k) }
      }
      $bytes.Add(("0x{0:X2}" -f $b))
    }
  }

  [void]$sb.AppendLine("// $($it.id): ${bw}x${bh}")
  [void]$sb.AppendLine("static const uint8_t $($it.id)_bmp[] PROGMEM = {")
  for ($i = 0; $i -lt $bytes.Count; $i += 16) {
    $end = [Math]::Min($i + 16, $bytes.Count)
    [void]$sb.AppendLine("  " + (($bytes.GetRange($i, $end - $i)) -join ", ") + ",")
  }
  [void]$sb.AppendLine("};")
  $enC = 'nullptr'
  if ($it.en) {
    $esc = $it.en -replace '\\', '\\\\' -replace '"', '\"'
    [void]$sb.AppendLine("static const char $($it.id)_en[] PROGMEM = `"$esc`";")
    $enC = "$($it.id)_en"
  }
  [void]$sb.AppendLine("static const BnText $($it.id) PROGMEM = { $bw, $bh, $($it.id)_bmp, $enC };")
  [void]$sb.AppendLine("")

  $rendered += [pscustomobject]@{ id = $it.id; w = $bw; h = $bh; on = $on; ox = $minX; oy = $minY }
  "{0,-18} {1,3} x {2,2}" -f $it.id, $bw, $bh
}

[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $OutH)).Path + "\" + (Split-Path $OutH -Leaf), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

# Preview: OLED er moto kalo background e neel pixel, 4x boro
$S = 4; $gap = 6
$totalH = ($rendered | ForEach-Object { $_.h * $S + $gap } | Measure-Object -Sum).Sum + $gap
$prev = New-Object System.Drawing.Bitmap((128 * $S + 2 * $gap), $totalH)
$pg = [System.Drawing.Graphics]::FromImage($prev)
$pg.Clear([System.Drawing.Color]::FromArgb(10, 10, 14))
$pix = New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(120, 200, 255))
$edge = New-Object System.Drawing.Pen([System.Drawing.Color]::FromArgb(40, 40, 50))
$yy = $gap
foreach ($r in $rendered) {
  $x0 = $gap + [int]((128 - $r.w) / 2) * $S
  $pg.DrawRectangle($edge, $gap - 1, $yy - 1, 128 * $S + 1, $r.h * $S + 1)
  for ($y = 0; $y -lt $r.h; $y++) {
    for ($x = 0; $x -lt $r.w; $x++) {
      if (($r.oy + $y) -lt $r.on.GetLength(1) -and $r.on[($r.ox + $x), ($r.oy + $y)]) { $pg.FillRectangle($pix, $x0 + $x * $S, $yy + $y * $S, $S - 1, $S - 1) }
    }
  }
  $yy += $r.h * $S + $gap
}
$pg.Dispose()
$prev.Save("$PreviewDir\bangla_preview.png", [System.Drawing.Imaging.ImageFormat]::Png)
$prev.Dispose()
"Preview: $PreviewDir\bangla_preview.png"
