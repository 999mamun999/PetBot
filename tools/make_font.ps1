# OLED er jonno porishkar English font: Windows font ke 1-bit hinted (pixel e bosano) kore Adafruit GFX font banay.
# Output: PetBot\pb_fonts.h  (PBTiny = Tahoma 9px, PBSmall = Tahoma 11px, PBBold = Tahoma Bold 13px)
# Chalano:  powershell -ExecutionPolicy Bypass -File tools\make_font.ps1
param([string]$OutH = "$PSScriptRoot\..\PetBot\pb_fonts.h")
Add-Type -AssemblyName System.Drawing

function Make-Font($name, $family, $px, $styleName) {
  $style = [System.Drawing.FontStyle]::$styleName
  $font = New-Object System.Drawing.Font($family, [float]$px, $style, [System.Drawing.GraphicsUnit]::Pixel)
  $ff = $font.FontFamily
  $asc = [int][Math]::Round($ff.GetCellAscent($style) * $px / $ff.GetEmHeight($style))
  $lineH = [int][Math]::Round($ff.GetLineSpacing($style) * $px / $ff.GetEmHeight($style))
  $fmt = [System.Drawing.StringFormat]::GenericTypographic.Clone()
  $fmt.FormatFlags = $fmt.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces
  $pad = 4; $S = [int]($px * 2 + $pad * 2)
  $bits = New-Object System.Collections.Generic.List[int]
  $glyphs = @()
  $measure = New-Object System.Drawing.Bitmap(8, 8); $mg = [System.Drawing.Graphics]::FromImage($measure)
  $mg.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
  for ($c = 32; $c -le 126; $c++) {
    $ch = [string][char]$c
    $adv = [int][Math]::Round($mg.MeasureString($ch, $font, [System.Drawing.PointF]::new(0, 0), $fmt).Width)
    if ($c -eq 32) { $adv = [Math]::Max(3, $adv) }
    $bmp = New-Object System.Drawing.Bitmap($S, $S)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::Black)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
    $g.DrawString($ch, $font, [System.Drawing.Brushes]::White, [float]$pad, [float]$pad, $fmt)
    $g.Dispose()
    $minX = $S; $minY = $S; $maxX = -1; $maxY = -1
    for ($y = 0; $y -lt $S; $y++) { for ($x = 0; $x -lt $S; $x++) {
      if ($bmp.GetPixel($x, $y).R -gt 128) { if ($x -lt $minX) { $minX = $x }; if ($x -gt $maxX) { $maxX = $x }; if ($y -lt $minY) { $minY = $y }; if ($y -gt $maxY) { $maxY = $y } }
    } }
    $off = [int]($bits.Count / 8)
    if ($maxX -lt 0) { $glyphs += ,@($off, 0, 0, $adv, 0, 0) }
    else {
      $w = $maxX - $minX + 1; $h = $maxY - $minY + 1
      $acc = New-Object System.Collections.Generic.List[int]
      for ($y = $minY; $y -le $maxY; $y++) { for ($x = $minX; $x -le $maxX; $x++) { $acc.Add([int]($bmp.GetPixel($x, $y).R -gt 128)) } }
      while ($acc.Count % 8) { $acc.Add(0) }
      foreach ($b in $acc) { $bits.Add($b) }
      $glyphs += ,@($off, $w, $h, ($w + ($minX - $pad) + 1), ($minX - $pad), ($minY - $pad - $asc))   # shob akkhorer pore ekoi 1 px faka
    }
    $bmp.Dispose()
  }
  $mg.Dispose(); $measure.Dispose()
  $bytes = @(); for ($i = 0; $i -lt $bits.Count; $i += 8) { $v = 0; for ($k = 0; $k -lt 8; $k++) { $v = ($v -shl 1) -bor $bits[$i + $k] }; $bytes += $v }
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.AppendLine("// $name = $family ${px}px $styleName (1-bit hinted)  ascent=$asc line=$lineH")
  [void]$sb.AppendLine("static const uint8_t ${name}Bitmaps[] PROGMEM = {")
  for ($i = 0; $i -lt $bytes.Count; $i += 24) { [void]$sb.AppendLine("  " + (($bytes[$i..([Math]::Min($i + 23, $bytes.Count - 1))] | % { "0x{0:X2}" -f $_ }) -join ",") + ",") }
  [void]$sb.AppendLine("};")
  [void]$sb.AppendLine("static const GFXglyph ${name}Glyphs[] PROGMEM = {")
  $c = 32; foreach ($gl in $glyphs) { [void]$sb.AppendLine(("  {{ {0,5}, {1,2}, {2,2}, {3,2}, {4,3}, {5,3} }},   // '{6}'" -f $gl[0], $gl[1], $gl[2], $gl[3], $gl[4], $gl[5], ([char]$c -replace '\\', 'bs'))); $c++ }
  [void]$sb.AppendLine("};")
  [void]$sb.AppendLine("static const GFXfont $name PROGMEM = { (uint8_t*)${name}Bitmaps, (GFXglyph*)${name}Glyphs, 0x20, 0x7E, $lineH };")
  [void]$sb.AppendLine("#define ${name}_ASC $asc")
  $capH = $glyphs[72 - 32][2]
  [void]$sb.AppendLine("#define ${name}_CAP $capH          // 'H' er uchchota: lekhar upor theke baseline")
  "$name : $family $px $styleName, ascent $asc, line $lineH, $($bytes.Count) byte" | Write-Host
  return $sb.ToString()
}

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine("// Auto-generated by tools/make_font.ps1 - OLED er jonno porishkar English font. Hate edit koro na.")
[void]$out.AppendLine("#pragma once")
[void]$out.AppendLine("#include <Adafruit_GFX.h>")
[void]$out.Append((Make-Font "PBTiny" "Tahoma" 9 "Regular"))
[void]$out.Append((Make-Font "PBSmall" "Tahoma" 11 "Regular"))
[void]$out.Append((Make-Font "PBBold" "Tahoma" 13 "Bold"))
[IO.File]::WriteAllText((Resolve-Path (Split-Path $OutH)).Path + "\pb_fonts.h", $out.ToString(), (New-Object Text.UTF8Encoding($false)))
"saved pb_fonts.h"
