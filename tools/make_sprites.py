# Pixel-art sprite: tools/sprites.txt (ASCII) -> PetBot/sprites.h (PROGMEM) + tools/preview/sprites.png
#   @naam            <- notun sprite
#   #  = sada pixel (jole)
#   o  = kalo pixel (pichhoner jinish muche dey: chokh, rekha, outline)
#   .  = swachchho (pichhon dekha jay)
# Chalano:  python tools\make_sprites.py
import pathlib, struct, zlib

ROOT = pathlib.Path(__file__).resolve().parent
src = (ROOT / "sprites.txt").read_text(encoding="utf-8").splitlines()

sprites, cur = [], None
for line in src:
    t = line.rstrip()
    if not t or t.startswith(";"):
        continue
    if t.startswith("@"):
        cur = [t[1:].strip(), []]
        sprites.append(cur)
    elif cur is not None:
        cur[1].append(t)

def pack(rows, ch, w):
    out = []
    for r in rows:
        r = r.ljust(w, ".")
        for b in range(0, w, 8):
            v = 0
            for k in range(8):
                if b + k < w and r[b + k] == ch:
                    v |= 0x80 >> k
            out.append(v)
    return out

h_lines = ["// Auto-generated by tools/make_sprites.py from tools/sprites.txt. Hate edit koro na.",
           "#pragma once", "#include <Arduino.h>",
           "struct Sprite { uint8_t w, h; const uint8_t* on; const uint8_t* off; };", ""]
total = 0
for name, rows in sprites:
    w, h = max(len(r) for r in rows), len(rows)
    bad = set("".join(rows)) - set("#o.")
    assert not bad, f"{name}: ojana akkhor {bad}"
    on, off = pack(rows, "#", w), pack(rows, "o", w)
    hasoff = any(off)
    total += len(on) + (len(off) if hasoff else 0)
    N = name.upper()
    h_lines.append(f"static const uint8_t SP_{N}_on[] PROGMEM = {{{','.join(str(x) for x in on)}}};")
    if hasoff:
        h_lines.append(f"static const uint8_t SP_{N}_off[] PROGMEM = {{{','.join(str(x) for x in off)}}};")
    h_lines.append(f"static const Sprite SPR_{N} PROGMEM = {{ {w}, {h}, SP_{N}_on, {'SP_' + N + '_off' if hasoff else 'nullptr'} }};")
(ROOT.parent / "PetBot" / "sprites.h").write_text("\n".join(h_lines) + "\n", encoding="utf-8")

# ---- preview PNG (PIL chara, nijei PNG banai) ----
S, PAD = 7, 8
cells = [(n, r, max(len(x) for x in r), len(r)) for n, r in sprites]
W = 1500
x = y = PAD; rowh = 0; pos = []
for n, r, w, h in cells:
    pw, ph = w * S, h * S + 12
    if x + pw > W - PAD:
        x = PAD; y += rowh + PAD; rowh = 0
    pos.append((x, y)); x += pw + PAD * 3; rowh = max(rowh, ph)
H = y + rowh + PAD
img = [[(70, 70, 70)] * W for _ in range(H)]
FONT = {}  # naam lekha bad (shudhu chhobi)
for (n, r, w, h), (px, py) in zip(cells, pos):
    for yy in range(h * S):
        for xx in range(w * S):
            img[py + 12 + yy][px + xx] = (12, 14, 20)
    for j, row in enumerate(r):
        for i, c in enumerate(row):
            col = (90, 196, 255) if c == "#" else ((40, 0, 0) if c == "o" else None)
            if col is None: continue
            for yy in range(S - 1):
                for xx in range(S - 1):
                    img[py + 12 + j * S + yy][px + i * S + xx] = col
    for xx in range(min(len(n) * 4, w * S)):            # naam er jayga te choto dag
        img[py + 4][px + xx] = (200, 200, 120)
raw = b"".join(b"\x00" + bytes(v for p in row for v in p) for row in img)
def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
(ROOT / "preview").mkdir(exist_ok=True)
(ROOT / "preview" / "sprites.png").write_bytes(png)
print(f"{len(sprites)} sprite, {total} byte flash -> sprites.h; preview: tools/preview/sprites.png")
for (n, r, w, h), (px, py) in zip(cells, pos):
    print(f"  {n:14s} {w:3d}x{h:<3d} @ {px},{py}")
