# Phone page (PetBot\web_page.h er WEB_PAGE) ke gzip kore PetBot\web_page_gz.h banay.
# Chhoto file (~6KB) robot theke druto ar nirapode pouchay (RAM kom thakleo kete jay na).
# upload.ps1 compile er age nijei eta chalay.
$src = Join-Path $PSScriptRoot "..\PetBot\web_page.h"
$dst = Join-Path $PSScriptRoot "..\PetBot\web_page_gz.h"
$t = [IO.File]::ReadAllText($src, [Text.Encoding]::UTF8)
$a = $t.IndexOf('WEB_PAGE[] PROGMEM = R"HTML(')
if ($a -lt 0) { throw "WEB_PAGE pawa jay ni" }
$a = $t.IndexOf('R"HTML(', $a) + 7
$b = $t.IndexOf(')HTML"', $a)
$html = $t.Substring($a, $b - $a)
$raw = [Text.Encoding]::UTF8.GetBytes($html)
$ms = New-Object IO.MemoryStream
$gz = New-Object IO.Compression.GZipStream($ms, [IO.Compression.CompressionMode]::Compress)
$gz.Write($raw, 0, $raw.Length); $gz.Close()
$bytes = $ms.ToArray()
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine("// Auto-generated by tools/make_web.ps1 (web_page.h er gzip). Hate edit koro na.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("static const uint8_t WEB_PAGE_GZ[] PROGMEM = {")
for ($i = 0; $i -lt $bytes.Length; $i += 20) {
  $end = [Math]::Min($i + 20, $bytes.Length)
  [void]$sb.AppendLine("  " + (($bytes[$i..($end - 1)] | % { "0x{0:X2}" -f $_ }) -join ",") + ",")
}
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("static const size_t WEB_PAGE_GZ_LEN = $($bytes.Length);")
[IO.File]::WriteAllText($dst, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
"web page: $($raw.Length) byte -> gzip $($bytes.Length) byte"
