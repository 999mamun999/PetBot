# Makes your own WiFi (OTA) upload password.
#   powershell -ExecutionPolicy Bypass -File tools\set_ota_password.ps1
# Creates:
#   tools\ota_password.txt   - the password (used by upload.ps1)     [ignored by git]
#   PetBot\secrets.h         - only its MD5 hash (compiled into robot) [ignored by git]
# Then upload once with the USB cable; after that WiFi upload works.
param([string]$Password = "")
$pwFile = Join-Path $PSScriptRoot "ota_password.txt"
$secret = Join-Path $PSScriptRoot "..\PetBot\secrets.h"
if (-not $Password) {
  $chars = 'abcdefghjkmnpqrstuvwxyzABCDEFGHJKMNPQRSTUVWXYZ23456789'.ToCharArray()
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create(); $bytes = New-Object byte[] 16; $rng.GetBytes($bytes)
  $Password = -join ($bytes | % { $chars[$_ % $chars.Length] })
}
$md5 = [System.Security.Cryptography.MD5]::Create()
$hash = -join ($md5.ComputeHash([Text.Encoding]::ASCII.GetBytes($Password)) | % { $_.ToString('x2') })
[IO.File]::WriteAllText($pwFile, $Password, (New-Object Text.UTF8Encoding($false)))
$h = "// Auto-generated by tools/set_ota_password.ps1 - keep private (ignored by git)`n#pragma once`n#define OTA_PASS_MD5 `"$hash`"`n"
[IO.File]::WriteAllText((Resolve-Path (Split-Path $secret)).Path + "\secrets.h", $h, (New-Object Text.UTF8Encoding($false)))
"OTA password saved to tools\ota_password.txt (keep it private)."
"PetBot\secrets.h created. Now upload once by USB: tools\upload.ps1"
